import { Card } from '../../components/ui/Card';
import { usePageTitle } from '../../components/ui/usePageTitle';
import { ANOMALY_CONFIG, NEAR_BUDGET_SHARE, PROJECTION_CONFIG } from '../../config/defaults';
import { ACTIONS } from '../../data/conservationActions';

export default function MethodologyPage() {
  usePageTitle('Methodology and limits');
  const a = ANOMALY_CONFIG;
  return (
    <>
      <div className="page-head">
        <h1>Methodology and limits</h1>
        <p>What the numbers in this app mean, how each one is calculated, and what the app cannot do.</p>
      </div>

      <Card title="Where the data comes from" tone="warn">
        <ul>
          <li><strong>Sample data</strong> is generated by a seeded program for about 35 days ending today. It models a household of about four using roughly 500 L a day. It is not measured. Two events are injected on purpose so the Waste Detective has something to find: one high-use day and one night with continuous use.</li>
          <li><strong>Entered by you</strong> means a daily total typed into History. The app cannot check it.</li>
          <li><strong>Estimate</strong> means calculated from past days. It is not a reading.</li>
          <li>This prototype is not connected to a water meter or sensor. It does not monitor anything live, and no figure is measured.</li>
        </ul>
      </Card>

      <Card title="Calculations">
        <div className="stack">
          <div>
            <h3>Weekly budget</h3>
            <p>A weekly budget is used as entered. A daily budget is multiplied by 7. All analysis uses Monday to Sunday weeks and litres.</p>
          </div>
          <div>
            <h3>Used so far, remaining, utilization</h3>
            <p>Used so far = sum of logged days from Monday through today. Remaining = budget − used (negative means over). Utilization = used ÷ budget, and is not shown when no budget is set. Days with no entry are left out, not counted as zero use.</p>
          </div>
          <div>
            <h3>Estimated end of week</h3>
            <p>
              Typical day = average of the up to {PROJECTION_CONFIG.baselineDays} logged days before today (at least {PROJECTION_CONFIG.minBaselineDays} are required).
              Expected rest of week = typical day × full days left after today + max(0, typical day − today's logged litres).
              Estimated total = used so far + expected rest of week. The range shown is plus or minus one standard deviation of daily use across the remaining days, and assumes days vary independently.
              Today is always treated as unfinished, so a daily total entered for today that is already complete may make the estimate slightly high.
              Estimates are rounded to the nearest 10 L. The method ignores weekday patterns, weather, guests and holidays.
            </p>
          </div>
          <div>
            <h3>Saving scenario</h3>
            <p>Water saved = expected rest of week × reduction. New total = used so far + expected rest × (1 − reduction). The reduction applies only to water not yet used. The reduction needed to meet the budget = (estimated total − budget) ÷ expected rest of week.</p>
          </div>
          <div>
            <h3>Projected status</h3>
            <p>Over budget if the estimate exceeds the budget; close to budget if it reaches {Math.round(NEAR_BUDGET_SHARE * 100)}% of it.</p>
          </div>
        </div>
      </Card>

      <Card title="Waste Detective rules">
        <div className="stack">
          <div>
            <h3>Unusually high day</h3>
            <p>Baseline = mean and sample standard deviation of the previous {a.baselineWindow} logged days (at least {a.minBaselineDays} needed). A day is flagged when its total is above mean + {a.sigma} × standard deviation <em>and</em> at least max({a.minExcessLitres} L, {Math.round(a.minExcessFraction * 100)}% of the mean) above the mean. The second condition stops tiny differences being flagged when past days were very steady. High severity means the excess is at least {Math.round(a.highExcessFraction * 100)}% of the mean.</p>
          </div>
          <div>
            <h3>Continuous night-time use</h3>
            <p>Uses hourly data between {String(a.overnight.startHour).padStart(2, '0')}:00 and {String(a.overnight.endHour + 1).padStart(2, '0')}:00. Flagged when {a.overnight.minConsecutiveHours} or more consecutive hours each use at least {a.overnight.minLitresPerHour} L. Expected use is the median overnight hour in the stored data × the number of flagged hours. High severity means the excess is {a.overnight.highLitres} L or more. Hourly data exists only in sample data here, because manual entry is per day.</p>
          </div>
          <div>
            <h3>What an alert means</h3>
            <p>An alert marks a suspicious pattern. It does not confirm a leak, and the app cannot tell a leak from a guest, a timer or a data entry mistake. Only the last {a.lookbackDays} days are checked, and all thresholds are simple defaults, not tuned or validated against real households.</p>
          </div>
        </div>
      </Card>

      <Card title="Ripple Challenge savings">
        <p>Estimated saving = number of units logged × litres per unit. The litres per unit below are planning assumptions with their basis stated. They are self-reported and not measured, and the app does not check that an action happened.</p>
        <div className="table-wrap" style={{ marginTop: 'var(--s3)' }}>
          <table>
            <caption className="sr-only">Assumed litres per unit for each challenge</caption>
            <thead><tr><th scope="col">Challenge</th><th scope="col">Unit</th><th scope="col" className="num">L per unit</th><th scope="col">Basis</th></tr></thead>
            <tbody>
              {ACTIONS.map((x) => (
                <tr key={x.id}><th scope="row">{x.title}</th><td>{x.unitLabel}</td><td className="num">{x.litresPerUnit}</td><td>{x.basis}</td></tr>
              ))}
            </tbody>
          </table>
        </div>
        <p className="small muted" style={{ marginTop: 'var(--s3)' }}>Only this household's entries are shown. There are no global rankings, other users or impact totals.</p>
      </Card>

      <Card title="Known limitations">
        <ul>
          <li>No live meter or sensor data. Everything is sample or typed in.</li>
          <li>Data is stored in this browser only. It is not backed up and does not sync between devices.</li>
          <li>Estimates are averages of past days. They are not forecasts and carry real uncertainty.</li>
          <li>Hourly analysis works only on sample data in this version.</li>
          <li>Challenge savings rest on stated assumptions and may be wrong for any given home.</li>
        </ul>
      </Card>
    </>
  );
}
